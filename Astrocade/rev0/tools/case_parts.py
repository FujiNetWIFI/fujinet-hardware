#!/usr/bin/env python3
"""case/board-parts.scad: every top-side part of the routed board as a box (its F.Fab body outline,
else its courtyard, and its datasheet height above F.Cu), so the shell's `check` view can prove no
part touches the shell.  KiCad board coordinates (mm, y down), heights in mm above the board's top.

Run after the board changes: python3 tools/case_parts.py   (needs KiCad's pcbnew module)
"""
import os, sys
import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
PRJ = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
import design as D  # noqa: E402

# maximum height above F.Cu per footprint (datasheet nominal + tolerance)
HEIGHT = {
    'C_0603_1608Metric': 0.95,            # CL10 0.8 +/- 0.1
    'C_0805_2012Metric': 1.45,            # CL21A226MAQNNNE 1.25 +/- 0.2
    'RPI_C0402': 0.6, 'RPI_C0402_wide': 0.6,
    'R_0603_1608Metric': 0.55, 'RPI_R0402': 0.4, 'R_Array_Convex_4x0603': 0.6,
    'LED_0603_1608Metric': 0.8,           # KT-0603G
    'LED_WS2812B-2020_PLCC4_2.0x2.0mm': 0.9,
    'SOT-23': 1.2, 'SOT-23-5': 1.45, 'SOT-363_SC-70-6': 1.1, 'TSOT-23-6': 1.1,
    'D_SOD-523': 0.8, 'D_SMA': 2.45,
    'QFN-28-1EP_5x5mm_P0.5mm_EP3.35x3.35mm': 0.9, 'RPI_RP2350A_QFN60': 0.9,
    'ESP32-S3-WROOM-1': 3.3,              # 3.1 +/- 0.15
    'Crystal_SMD_3225-4Pin_3.2x2.5mm': 1.0,
    'L_Sunlord_SWPA4030S': 3.1, 'RPI_L_AOTA-B201610S3R3': 1.0,
    'USB_C_Receptacle_HRO_TYPE-C-31-M-12': 3.31,
    'TF-SMD_TF-015': 2.0,
    'SW_SPST_TL3342': 1.5,                # SKQGABE010: 0.8 body, the 2 mm stem to 1.5
    'TestPoint_Pad_D1.5mm': 0.05,
}
SKIP = ('MountingHole', 'Fiducial', 'Astrocade_Cart_Edge_26')   # flat copper or a hole


def body_box(fp):
    """bbox of the F.Fab outline (the body), else of the courtyard, in board mm."""
    xs, ys = [], []
    for g in fp.GraphicalItems():
        if g.GetLayer() == pcbnew.F_Fab and g.GetClass() in ('PCB_SHAPE', 'FP_SHAPE'):
            b = g.GetBoundingBox()
            xs += [b.GetLeft(), b.GetRight()]
            ys += [b.GetTop(), b.GetBottom()]
    if not xs:
        b = fp.GetCourtyard(pcbnew.F_CrtYd).BBox()
        xs, ys = [b.GetLeft(), b.GetRight()], [b.GetTop(), b.GetBottom()]
    return min(xs) / 1e6, min(ys) / 1e6, max(xs) / 1e6, max(ys) / 1e6


def main():
    board = pcbnew.LoadBoard(os.path.join(PRJ, D.PROJECT + '.kicad_pcb'))
    rows, missing = [], []
    for fp in sorted(board.GetFootprints(), key=lambda f: f.GetReference()):
        name = fp.GetFPIDAsString().split(':')[-1]
        if fp.IsFlipped():
            missing.append('%s is on the bottom side' % fp.GetReference())
            continue
        if name.startswith(SKIP):
            continue
        if name not in HEIGHT:
            missing.append('%s %s has no height' % (fp.GetReference(), name))
            continue
        x0, y0, x1, y1 = body_box(fp)
        rows.append('    [%.3f, %.3f, %.3f, %.3f, %.2f, "%s"]' % (x0, y0, x1, y1, HEIGHT[name], fp.GetReference()))
    if missing:
        sys.exit('case_parts: ' + '; '.join(missing))
    out = ['// GENERATED by tools/case_parts.py from the routed board -- do not edit.',
           '// Top-side parts: [x0, y0, x1, y1, height above F.Cu, ref], KiCad board mm (body outline,',
           '// else courtyard).  The shell\'s "check" view intersects these with both halves.',
           'board_parts = [', ',\n'.join(rows), '];', '']
    open(os.path.join(PRJ, 'case', 'board-parts.scad'), 'w').write('\n'.join(out))
    print('case_parts: %d parts -> case/board-parts.scad' % len(rows))


if __name__ == '__main__':
    main()
