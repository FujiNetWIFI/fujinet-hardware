PRJ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(PRJ, 'tools'))
import design as D
import placement as PL

K = lambda *keys: [D.KEY[k] for k in keys]
G = lambda *ns: [p for n in ns for p in (n, '*/' + n)]
HOLES = ['H%d' % (i + 1) for i in range(len(PL.HOLES))]

cfg = {
    'version': 1,
    'project': {'name': 'FujiNet-ChannelF Rev0', 'revision': '0', 'company': 'FujiNet', 'market': 'us',
                'emc_standard': 'fcc-class-b', 'pdn_transient_current_a': 0.5},
    'preferred_suppliers': ['lcsc'],
    'bom': {'field_priority': ['MPN', 'LCSC'], 'group_by': 'value+footprint'},
    'design_intent': {'product_class': 'prototype', 'target_market': 'hobby', 'ipc_class': 2,
                      'preferred_passive_size': '0603', 'operating_temp_range': [0, 70]},
    'analysis': {
        'output_dir': 'analysis', 'retention': 5, 'auto_diff': True, 'track_in_git': False,
        'power_rails': {
            # a divider node that only looks like a rail by name
            'ignore': G('VBUS_SNS'),
            'voltage_overrides': {'+3V3_RP': 3.3, '+3V3': 3.3, '+5V': 5.0, 'CONS_5V': 5.0, 'VBUS': 5.0,
                                  'DVDD': 1.1}}},
    'suppressions': [
        {'rule_id': 'RS-001', 'nets': G('VBUS_SNS'),
         'reason': 'Divider node (22k / 47k from VBUS) into the CP2102N VBUS sense pin, not a rail.'},
        {'rule_id': 'PU-001', 'components': K('U_UART'),
         'reason': 'CP2102N CHREN / CHR0 / CHR1 are battery-charger outputs (datasheet 4.3.4), unused and left open '
                   'as in the ESP32-S3-DevKitC-1 reference.'},
        {'rule_id': 'LB-001',
         'reason': "Hierarchical label + sheet pin of the same net on two sheets (the root block diagram's wiring); "
                   'KiCad joins them by design.'},
        {'rule_id': 'CG-AUD', 'components': K('J_EDGE'),
         'reason': "Console-defined 22-contact Videocart edge: two GND contacts (1, 2) by Fairchild's pinout."},
        {'rule_id': 'EP-AUD', 'components': K('J_EDGE', 'J_SD'),
         'reason': 'J_EDGE is the console bus (no Videocart carries ESD parts; the SN74LVC4245A A port is 2 kV HBM); '
                   'J_SD (microSD) sits inside the shell.'},
        {'rule_id': 'DC-002', 'components': K('U_AUTOPROG'),
         'reason': 'UMH3N is a dual pre-biased transistor (esptool auto-program); it has no supply pin to decouple.'},
        {'rule_id': 'KO-001', 'components': K('J_EDGE', 'U_S3') + HOLES,
         'reason': 'Deliberate rule areas: the tab keep-outs forbid tracks, vias and pour but allow pads (the gold '
                   "fingers belong there); the S3 antenna keep-out is the module footprint's own; the boss keep-outs "
                   'keep copper off the holes inside them.'},
        {'rule_id': 'PM-002', 'components': K('J_EDGE', 'J_SD', 'J_USB', 'U_S3'),
         'reason': 'At the edge by design: the cart fingers, the microSD and USB-C mouths on the grip edge, the '
                   'ESP32-S3 antenna flush with the grip edge over its keep-out.'},
        {'rule_id': 'CC-002',
         'reason': "Signal nets necked down to 0.15 mm only for their last link at the RP2040's 0.4 mm-pitch pins "
                   '(finish_route --neck); logic currents of a few mA.'},
    ],
}
hdr = ('// kicad-happy project config for FujiNet-ChannelF Rev0 (JSONC) -- GENERATED by tools/audit/make_happy_config.py\n'
       '// from tools/design.py keys; do not edit.  kicad-happy 2.2.1 applies suppressions in the EMC and thermal\n'
       '// analyzers only.  Triage of every finding: docs/design-review-rev0.md.\n')
open(os.path.join(PRJ, '.kicad-happy.json'), 'w').write(hdr + json.dumps(cfg, indent=2) + '\n')
print('.kicad-happy.json: %d suppressions' % len(cfg['suppressions']))
